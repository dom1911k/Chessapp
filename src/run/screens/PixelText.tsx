/** Pixel heading. `size` = one font pixel in CSS px. Long text wraps at spaces if `maxWidth` is set. */
export function PixelText({ text, size = 3, color = 'var(--gold-2)', glow = true, className = '', style, maxWidth }: { text: string; size?: number; color?: string; glow?: boolean; className?: string; style?: CSSProperties; maxWidth?: number }) {
  const up = text.toUpperCase();
  // Simple word wrap by character budget.
  const lines: string[] = [];
  if (maxWidth) {
    const per = Math.max(4, Math.floor(maxWidth / (6 * size)));
    let cur = '';
    for (const w of up.split(' ')) {
      if ((cur + ' ' + w).trim().length > per && cur) {
        lines.push(cur);
        cur = w;
      } else cur = (cur + ' ' + w).trim();
    }
    if (cur) lines.push(cur);
  } else lines.push(up);
  const w = Math.max(...lines.map((l) => l.length)) * 6 - 1;
  const h = lines.length * 9 - 2;
  return (
    <svg
      width={w * size}
      height={h * size}
      viewBox={`0 0 ${w} ${h}`}
      shapeRendering="crispEdges"
      className={className}
      role="img"
      aria-label={text}
      style={{ ...(glow ? { filter: `drop-shadow(0 0 ${size * 2}px ${color}) drop-shadow(0 ${size}px 0 rgba(0,0,0,.65))` } : {}), overflow: 'visible', ...style }}
    >
      {lines.flatMap((line, li) => {
        const off = Math.floor(((Math.max(...lines.map((l) => l.length)) - line.length) * 6) / 2);
        return line.split('').flatMap((ch, i) => {
          const g = G[ch] ?? G['?'];
          const rects = [];
          for (let k = 0; k < 35; k++) if (g[k] === '1') rects.push(<rect key={`${li}-${i}-${k}`} x={off + i * 6 + (k % 5)} y={li * 9 + Math.floor(k / 5)} width={1} height={1} fill={color} />);
          return rects;
        });
      })}
    </svg>
  );
}
